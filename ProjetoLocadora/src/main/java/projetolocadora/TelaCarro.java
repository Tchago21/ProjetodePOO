    private void carregarCarros() {

    DefaultTableModel modelo =
            (DefaultTableModel) tabelaCarros.getModel();

    modelo.setRowCount(0);    
    
    carros = carroDAO.listar();

    for (Carro carro : carroDAO.listar()) {

        modelo.addRow(new Object[]{
        carro.getMarca(),
        carro.getModelo(),
        carro.getPlaca(),
        carro.getAno(),
        carro.getValorDiaria(),
        carro.isDisponivel() ? "Sim" : "Não"
    });
    }
}
