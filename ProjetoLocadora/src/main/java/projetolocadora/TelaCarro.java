    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
    String marca = txtMarca.getText();
    String modelo = txtModelo.getText();
    String placa = txtPlaca.getText();
    String anoTexto = txtAno.getText();
    String valorTexto = txtValorDiaria.getText();

    if (marca.isEmpty()
            || modelo.isEmpty()
            || placa.isEmpty()
            || anoTexto.isEmpty()
            || valorTexto.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Preencha todos os campos."
        );

        return;
    }

    try {

        int ano = Integer.parseInt(anoTexto);

        double valorDiaria =
                Double.parseDouble(
                        valorTexto.replace(",", ".")
                );

        Carro carro = new Carro(
            marca,
            modelo,
            placa,
            ano,
            valorDiaria,
            true
        );

        carroDAO.inserir(carro);

        JOptionPane.showMessageDialog(
                this,
                "Carro cadastrado com sucesso!"
        );

        limparCampos();
        carregarCarros();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Ano ou valor da diária inválido.",
                "Erro",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
    int linha = tabelaCarros.getSelectedRow();

    if (linha == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Selecione um carro na tabela."
        );

        return;
    }

    Carro carro = carros.get(linha);

    int id = carro.getId();

    int resposta = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir este carro?",
            "Confirmar exclusão",
            JOptionPane.YES_NO_OPTION
    );

    if (resposta == JOptionPane.YES_OPTION) {

        boolean excluido = carroDAO.excluir(id);

        if (excluido) {

            JOptionPane.showMessageDialog(
                    this,
                    "Carro excluído com sucesso!"
            );

            carregarCarros();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Não é possível excluir este carro.\n"
                    + "Existem locações vinculadas a ele.",
                    "Exclusão não permitida",
                    JOptionPane.WARNING_MESSAGE
            );
        }
    }
    }//GEN-LAST:event_btnExcluirActionPerformed

